import { describe, expect, it } from 'vitest';
import * as XLSX from 'xlsx';
import { readDtoolsFile } from './dtoolsImport';

const HEADER = [
  'Approved',
  'Entity',
  'Date',
  'Resource',
  'Resource Email',
  'Client Name',
  'Project Name',
  'Project Number',
  'Project Manager',
  'Name',
  'Number',
  'Duration',
  'Created On',
  'Updated On',
  'Updated By',
];

function dataRow(date: string | Date, duration: number, taskNumber: string): unknown[] {
  return [
    'True',
    'Task',
    date,
    'Inspector A',
    'a@example.com',
    'Example Client',
    'I&T - FA Example Building Annual Fire Alarm Inspection 2025 1 of 3',
    '25-1000',
    'Drew Cassidy',
    'I&T - FA Example Building Annual Fire Alarm Inspection 2025 1 of 3',
    taskNumber,
    duration,
    '5/2/2025',
    '5/2/2025',
    'Inspector A',
  ];
}

function workbookFile(sheets: Array<{ name: string; rows: unknown[][] }>): File {
  const workbook = XLSX.utils.book_new();
  for (const sheet of sheets) {
    XLSX.utils.book_append_sheet(
      workbook,
      XLSX.utils.aoa_to_sheet(sheet.rows),
      sheet.name,
    );
  }
  const buffer = XLSX.write(workbook, { type: 'array', bookType: 'xlsx' });
  return new File([buffer], 'timesheet.xlsx', {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
}

describe('D-Tools file import', () => {
  it('finds offset headers and preserves physical row numbers including leading blank rows and columns', async () => {
    const workbook = XLSX.utils.book_new();
    const sheet = XLSX.utils.aoa_to_sheet([['Export generated by D-Tools']]);
    XLSX.utils.sheet_add_aoa(sheet, [HEADER, dataRow('5/1/2025', 0.46666667, '75000'), [], dataRow('5/2/2025', 8.5, '75001')], { origin: 'C5' });
    XLSX.utils.book_append_sheet(workbook, sheet, 'Offset');
    const parsed = await readDtoolsFile(new File([XLSX.write(workbook, { type: 'array', bookType: 'xlsx' })], 'offset.xlsx'));
    expect(parsed.rows.map((row) => row.sourceRow)).toEqual([6, 8]);
    expect(parsed.rows.map((row) => row.duration)).toEqual([0.46666667, 8.5]);
    expect(parsed.dataset.sheetName).toBe('Offset');
  });

  it('refuses multiple timesheet sheets instead of silently importing only the first', async () => {
    await expect(readDtoolsFile(workbookFile([
      { name: '2024', rows: [HEADER, dataRow('5/1/2024', 8, '75000')] },
      { name: '2025', rows: [HEADER, dataRow('5/1/2025', 9, '75001')] },
    ]))).rejects.toThrow(/Multiple timesheet worksheets/);
  });

  it('rejects time-formatted durations instead of assuming decimal hours', async () => {
    const workbook = XLSX.utils.book_new();
    const sheet = XLSX.utils.aoa_to_sheet([HEADER, dataRow('5/1/2025', 0.5, '75000')]);
    sheet.L2.z = '[h]:mm';
    XLSX.utils.book_append_sheet(workbook, sheet, 'Timesheets');
    await expect(readDtoolsFile(new File([XLSX.write(workbook, { type: 'array', bookType: 'xlsx' })], 'clock.xlsx'))).rejects.toThrow(/decimal hours/);
  });

  it('honors the 1904 date system and numeric project identifier display formats', async () => {
    const workbook = XLSX.utils.book_new();
    const sheet = XLSX.utils.aoa_to_sheet([HEADER, dataRow('5/1/2025', 8, '75000')]);
    sheet.C2 = { t: 'n', v: 44316, z: 'm/d/yyyy' };
    sheet.H2 = { t: 'n', v: 123, z: '000000' };
    workbook.Workbook = { WBProps: { date1904: true } };
    XLSX.utils.book_append_sheet(workbook, sheet, 'Timesheets');
    const parsed = await readDtoolsFile(new File([XLSX.write(workbook, { type: 'array', bookType: 'xlsx' })], '1904.xlsx'));
    expect(parsed.rows[0].date).toBe('2025-05-01');
    expect(parsed.rows[0].projectNumber).toBe('000123');
  });
  it('reads XLSX and preserves the physical Excel row across a blank spacer row', async () => {
    const parsed = await readDtoolsFile(
      workbookFile([
        {
          name: 'Timesheets',
          rows: [
            HEADER,
            dataRow('5/1/2025', 8, '75000'),
            [],
            dataRow('5/2/2025', 7.5, '75001'),
          ],
        },
      ]),
      1_700_000_000_000,
    );
    expect(parsed.rows).toHaveLength(2);
    expect(parsed.rows.map((row) => row.sourceRow)).toEqual([2, 4]);
    expect(parsed.dataset.fileType).toBe('xlsx');
    expect(parsed.dataset.sheetName).toBe('Timesheets');
    expect(parsed.dataset.validRows).toBe(2);
  });

  it('skips a cover worksheet and uses the first sheet with timesheet columns', async () => {
    const parsed = await readDtoolsFile(
      workbookFile([
        { name: 'Cover', rows: [['D-Tools export'], ['Prepared by Omni']] },
        {
          name: 'Timesheets',
          rows: [HEADER, dataRow('5/1/2025', 8, '75000')],
        },
      ]),
    );
    expect(parsed.dataset.sheetName).toBe('Timesheets');
    expect(parsed.rows).toHaveLength(1);
  });

  it('parses real Date cells in XLSX without shifting the calendar day', async () => {
    const parsed = await readDtoolsFile(
      workbookFile([
        {
          name: 'Timesheets',
          rows: [HEADER, dataRow(new Date(2025, 4, 1), 8, '75000')],
        },
      ]),
    );
    expect(parsed.rows[0].date).toBe('2025-05-01');
  });

  it('produces the same fingerprint for the same file and a new dataset id each time', async () => {
    const file = workbookFile([
      { name: 'Timesheets', rows: [HEADER, dataRow('5/1/2025', 8, '75000')] },
    ]);
    const first = await readDtoolsFile(file);
    const second = await readDtoolsFile(file);
    expect(first.dataset.fingerprint).toBe(second.dataset.fingerprint);
    expect(first.dataset.id).not.toBe(second.dataset.id);
  });

  it('rejects an empty CSV and an unsupported extension', async () => {
    await expect(readDtoolsFile(new File([''], 'empty.csv'))).rejects.toThrow(/empty/);
    await expect(readDtoolsFile(new File(['abc'], 'notes.txt'))).rejects.toThrow(
      /csv or .xlsx/,
    );
  });
});
